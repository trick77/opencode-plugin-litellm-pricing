// Regenerates src/models-dev-snapshot.ts — the price table shipped inside the
// package. Run it before tagging a release (see AGENTS.md), so a release never
// ships a snapshot older than itself:
//
//   npm run update-snapshot
//
// The snapshot exists so startup never has to wait on the network: with a table
// always in hand, the fetch is only ever a background refresh. It is a floor —
// the on-disk cache and a live fetch both take precedence over it.
//
// Only the providers the matcher considers, and only the fields
// `toCatalogFields` reads: 3.6 MB of published table becomes ~34 KB.

import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const MODELS_DEV_URL = 'https://models.dev/api.json'

// Must stay in step with PREFERRED_PROVIDERS in src/catalog.ts. Widening it
// there without regenerating here leaves the snapshot unable to price the new
// provider until the first successful fetch.
const PREFERRED_PROVIDERS = ['azure', 'openai']

// Must stay in step with toCatalogFields / toCost in src/catalog.ts. A field
// dropped here is a field that silently disappears from the shipped prices.
const KEEP = ['id', 'cost', 'limit', 'reasoning', 'tool_call', 'attachment', 'modalities']

/** Sort keys so an unchanged table produces no diff. */
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sorted(value[k])]),
    )
  }
  return value
}

const res = await fetch(MODELS_DEV_URL)
if (!res.ok) throw new Error(`${MODELS_DEV_URL} returned HTTP ${res.status}`)
const table = await res.json()

const snapshot = {}
for (const id of PREFERRED_PROVIDERS) {
  const provider = table[id]
  if (!provider?.models) throw new Error(`models.dev has no "${id}" provider — refusing to ship an empty snapshot`)
  const models = {}
  for (const [key, model] of Object.entries(provider.models)) {
    models[key] = Object.fromEntries(KEEP.filter((k) => k in model).map((k) => [k, model[k]]))
  }
  // `id` is what buildFromProviders keys on; without it the entry is dropped
  // and the snapshot prices nothing.
  snapshot[id] = { id, models }
}

const count = Object.values(snapshot).reduce((n, p) => n + Object.keys(p.models).length, 0)
if (count === 0) throw new Error('snapshot would contain no models')

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'models-dev-snapshot.ts')
await writeFile(
  out,
  `// GENERATED by \`npm run update-snapshot\` — do not edit by hand.
//
// The models.dev price table, trimmed to the providers and fields this plugin
// reads, shipped so that a fresh install prices models without waiting on the
// network. A floor only: the on-disk cache and a live fetch both win over it.
//
// Fetched ${new Date().toISOString().slice(0, 10)} from ${MODELS_DEV_URL} — ${count} models.

export const MODELS_DEV_SNAPSHOT: Record<string, unknown> = ${JSON.stringify(sorted(snapshot), null, 2)}
`,
  'utf8',
)

console.log(`wrote ${out} — ${count} models`)
