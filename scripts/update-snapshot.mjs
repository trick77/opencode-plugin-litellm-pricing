// Regenerates src/price-table-snapshot.ts — the price table shipped inside the
// package. Run it before tagging a release (see AGENTS.md), so a release never
// ships a snapshot older than itself:
//
//   npm run update-snapshot
//
// The snapshot exists so startup never has to wait on the network: with a table
// always in hand, the fetch is only ever a background refresh. It is a floor —
// the on-disk cache and a live fetch both take precedence over it, including
// for anyone pointing `options.pricingURL` at their own enriched table.
//
// Only the fields `toCatalogFields`/`buildCost` read: ~1.7 MB of published
// table becomes ~700 KB. Entries are NOT filtered by provider — the exact-key
// matcher looks at all of them.

import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Must stay in step with DEFAULT_PRICE_TABLE_URL in src/catalog.ts.
const PRICE_TABLE_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'

// LiteLLM's documentation stub, not a model.
const SAMPLE_SPEC_KEY = 'sample_spec'

// Must stay in step with KEEP_FIELDS in src/catalog.ts. A field dropped here is
// a field that silently disappears from the shipped prices.
const KEEP = [
  'litellm_provider',
  'max_input_tokens',
  'max_output_tokens',
  'max_tokens',
  'input_cost_per_token',
  'output_cost_per_token',
  'cache_read_input_token_cost',
  'cache_creation_input_token_cost',
  'input_cost_per_token_above_200k_tokens',
  'output_cost_per_token_above_200k_tokens',
  'cache_read_input_token_cost_above_200k_tokens',
  'cache_creation_input_token_cost_above_200k_tokens',
  'supports_function_calling',
  'supports_reasoning',
  'supports_vision',
  'supports_pdf_input',
  'supports_audio_input',
]

/** Sort keys so an unchanged table produces no diff. */
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sorted(value[k])]),
    )
  }
  return value
}

const res = await fetch(PRICE_TABLE_URL)
if (!res.ok) throw new Error(`${PRICE_TABLE_URL} returned HTTP ${res.status}`)
const table = await res.json()

const snapshot = {}
for (const [key, entry] of Object.entries(table)) {
  if (key === SAMPLE_SPEC_KEY) continue
  if (!entry || typeof entry !== 'object' || Array.isArray(entry)) continue
  const kept = Object.fromEntries(KEEP.filter((k) => k in entry).map((k) => [k, entry[k]]))
  if (Object.keys(kept).length > 0) snapshot[key] = kept
}

const count = Object.keys(snapshot).length
if (count === 0) throw new Error('snapshot would contain no models')
// A table that lost the providers the substring matcher uses would still be
// non-empty while pricing almost nothing by name.
for (const provider of ['azure', 'openai']) {
  const n = Object.values(snapshot).filter((e) => e.litellm_provider === provider).length
  if (n === 0) throw new Error(`no "${provider}" entries — refusing to ship a crippled snapshot`)
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'price-table-snapshot.ts')
await writeFile(
  out,
  `// GENERATED by \`npm run update-snapshot\` — do not edit by hand.
//
// LiteLLM's published price table, trimmed to the fields this plugin reads,
// shipped so that a fresh install prices models without waiting on the network.
// A floor only: the on-disk cache and a live fetch both win over it.
//
// Fetched ${new Date().toISOString().slice(0, 10)} from ${PRICE_TABLE_URL} — ${count} models.

export const PRICE_TABLE_SNAPSHOT: Record<string, unknown> = ${JSON.stringify(sorted(snapshot))}
`,
  'utf8',
)

console.log(`wrote ${out} — ${count} models`)
